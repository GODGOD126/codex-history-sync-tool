function applyText() {
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = text[node.dataset.i18n] || "";
  });
}

function log(message) {
  const timestamp = new Date().toLocaleTimeString("zh-CN", { hour12: false });
  elements.logOutput.textContent += `[${timestamp}] ${message}\n`;
  elements.logOutput.scrollTop = elements.logOutput.scrollHeight;
}

function scopePayload() {
  if (!elements.scopeToggle.checked) return {};
  const cwd = elements.cwdInput.value.trim();
  if (!cwd) {
    throw new Error(text.scopePathRequired);
  }
  return { cwd };
}

function parseBody(options) {
  if (!options.body) return {};
  return typeof options.body === "string" ? JSON.parse(options.body) : options.body;
}

function tauriCore() {
  return window.__TAURI__ && window.__TAURI__.core;
}

async function tauriApi(path, options = {}) {
  const core = tauriCore();
  const url = new URL(path, window.location.origin);
  const body = parseBody(options);
  if (url.pathname === "/api/doctor") {
    return core.invoke("backend_doctor");
  }
  if (url.pathname === "/api/status") {
    return core.invoke("backend_status", { cwd: url.searchParams.get("cwd") || null });
  }
  if (url.pathname === "/api/sync/preview") {
    return core.invoke("backend_sync_preview", { cwd: body.cwd || null });
  }
  if (url.pathname === "/api/sync") {
    return core.invoke("backend_sync", { cwd: body.cwd || null });
  }
  if (url.pathname === "/api/backup") {
    return core.invoke("backend_backup");
  }
  if (url.pathname === "/api/restore/preview") {
    return core.invoke("backend_restore_preview", { backup: body.backup || null });
  }
  if (url.pathname === "/api/restore") {
    return core.invoke("backend_restore", { backup: body.backup || null });
  }
  if (url.pathname === "/api/verify") {
    return core.invoke("backend_verify", { backup: body.backup || null });
  }
  if (url.pathname === "/api/manifest") {
    return core.invoke("backend_manifest", { backup: body.backup || null });
  }
  if (url.pathname === "/api/backups/open") {
    return core.invoke("open_backup_dir");
  }
  if (url.pathname === "/api/manifest/open") {
    return core.invoke("open_manifest", { backup: body.backup || null });
  }
  throw new Error(`${text.unknownRoute}: ${url.pathname}`);
}

async function api(path, options = {}) {
  const payload = tauriCore()
    ? await tauriApi(path, options)
    : await fetch(path, {
        headers: { "content-type": "application/json" },
        ...options,
      }).then((response) => response.json());
  if (!options.allowFailure && !payload.ok && payload.error) {
    throw new Error(payload.error);
  }
  return payload;
}

function renderStatus(status) {
  const pendingCount = status.movable_threads ?? 0;
  state.status = status;
  state.selectedBackup = null;
  elements.threadCount.textContent = status.total_threads ?? "--";
  elements.scopeCount.textContent = status.cwd_filter ? `${status.scoped_threads}/${status.total_threads}` : text.all;
  elements.pendingCount.textContent = `${pendingCount}`;
  elements.pendingBadge.textContent = pendingCount > 0 ? `${pendingCount} ${text.pending}` : text.completed;
  if (elements.sidePending) {
    elements.sidePending.textContent = `${pendingCount} ${text.pending}`;
  }

  elements.providerRows.innerHTML = "";
  for (const row of status.provider_counts || []) {
    const tr = document.createElement("tr");
    tr.innerHTML = `<td>${row.provider}</td><td>${row.count}</td><td>${text.database}</td>`;
    elements.providerRows.appendChild(tr);
  }
  for (const row of status.session_provider_counts || []) {
    const tr = document.createElement("tr");
    tr.innerHTML = `<td>${row.provider}</td><td>${row.count}</td><td>${text.sessionFile}</td>`;
    elements.providerRows.appendChild(tr);
  }

  elements.backupList.innerHTML = "";
  for (const backup of status.backups || []) {
    const card = document.createElement("button");
    card.className = "backup-card";
    card.type = "button";
    card.innerHTML = `<strong>${backup.name}</strong><span>${backup.modified_at}${backup.manifest_exists ? ` · ${text.manifestReady}` : ""}</span>`;
    card.addEventListener("click", () => {
      state.selectedBackup = backup.path;
      resetRestorePreview();
      document.querySelectorAll(".backup-card").forEach((item) => item.classList.remove("selected"));
      card.classList.add("selected");
      setWriteState();
      log(`${text.selectedBackup}: ${backup.name}`);
    });
    elements.backupList.appendChild(card);
  }
}

function setWriteState() {
  const canWrite = state.doctorOk;
  const hasScope = !elements.scopeToggle.checked || Boolean(elements.cwdInput.value.trim());
  elements.dryRunButton.disabled = !hasScope;
  elements.backupButton.disabled = !canWrite;
  elements.syncButton.disabled = !canWrite || !hasScope || !state.syncPreviewReady;
  elements.restoreSelectedButton.disabled =
    !canWrite ||
    !state.restorePreviewVerified ||
    !state.selectedBackup ||
    state.restorePreviewKind !== "selected" ||
    state.restorePreviewBackupPath !== state.selectedBackup;
  elements.restoreLatestButton.disabled =
    !canWrite || !state.restorePreviewVerified || state.restorePreviewKind !== "latest" || !state.restorePreviewBackupPath;
  elements.manifestButton.disabled = !state.selectedBackup;
}

function resetRestorePreview() {
  state.restorePreviewToken = null;
  state.restorePreviewBackupPath = null;
  state.restorePreviewKind = null;
  state.restorePreviewVerified = false;
}

async function doctor() {
  const result = await api("/api/doctor", { allowFailure: true });
  state.doctorOk = result.ok !== false;
  elements.doctorStatus.textContent = state.doctorOk ? text.ready : text.blocked;
  const failed = (result.checks || []).filter((item) => item.required && !item.ok);
  if (failed.length) {
    log(`${text.doctorFailed}: ${failed.map((item) => item.name).join(", ")}`);
  } else {
    log(text.doctorOk);
  }
  setWriteState();
}

async function refresh() {
  const params = new URLSearchParams();
  const scope = scopePayload();
  if (scope.cwd) params.set("cwd", scope.cwd);
  const status = await api(`/api/status?${params.toString()}`);
  renderStatus(status);
  state.syncPreviewReady = false;
  resetRestorePreview();
  setWriteState();
  log(`${text.statusRefreshed}: ${status.movable_threads} ${text.pending}`);
}

async function dryRun() {
  const preview = await api("/api/sync/preview", {
    method: "POST",
    body: JSON.stringify(scopePayload()),
  });
  renderStatus(preview.status);
  state.syncPreviewReady = true;
  setWriteState();
  log(`${text.previewResult}: ${text.db} ${preview.would_update_database_threads}, ${text.sessionFiles} ${preview.would_update_session_files}, ${text.index} ${preview.would_add_session_index_entries}`);
}

async function syncNow() {
  if (!state.syncPreviewReady) {
    log(text.needSyncPreview);
    return;
  }
  const confirmed = window.confirm(text.confirmSync);
  if (!confirmed) return;
  const result = await api("/api/sync", {
    method: "POST",
    body: JSON.stringify(scopePayload()),
  });
  renderStatus(result.status);
  state.syncPreviewReady = false;
  resetRestorePreview();
  setWriteState();
  log(`${text.syncComplete}: ${text.db} ${result.updated_rows}, ${text.sessionFiles} ${result.updated_session_files}, ${text.createBackup} ${result.backup_path}`);
}

async function backup() {
  const result = await api("/api/backup", { method: "POST", body: "{}" });
  log(`${text.backupComplete}: ${result.backup_path}`);
  if (result.manifest_path) log(`${text.manifest}: ${result.manifest_path}`);
  resetRestorePreview();
  await refresh();
}

async function previewRestore(backupOverride = undefined) {
  const backupPath = backupOverride === undefined ? state.selectedBackup : backupOverride;
  const result = await api("/api/restore/preview", {
    method: "POST",
    body: JSON.stringify({ backup: backupPath }),
  });
  state.restorePreviewToken = result.restored_from;
  state.restorePreviewBackupPath = result.restored_from;
  state.restorePreviewKind = backupPath ? "selected" : "latest";
  state.restorePreviewVerified = result.verification?.verified === true;
  setWriteState();
  const comparison = result.comparison || {};
  const delta = typeof comparison.thread_count_delta === "number"
    ? comparison.thread_count_delta
    : (result.backup_thread_count ?? 0) - (result.current_thread_count ?? 0);
  const deltaText = delta > 0 ? `+${delta}` : `${delta}`;
  const ownershipText = comparison.provider_counts_will_change || comparison.model_counts_will_change
    ? text.comparisonChanged
    : text.comparisonSame;
  const verificationText = state.restorePreviewVerified ? text.verificationPassed : text.verificationFailed;
  log(`${text.restorePreviewLog}: ${text.currentThreads} ${result.current_thread_count ?? "--"}, ${text.backupThreads} ${result.backup_thread_count ?? "--"}, ${text.threadDelta} ${deltaText}, ${verificationText}, ${result.restorable_session_files} ${text.restorableFiles}, ${ownershipText}`);
}

async function restoreBackup(kind) {
  const isLatest = kind === "latest";
  const expectedBackupPath = isLatest ? state.restorePreviewBackupPath : state.selectedBackup;
  const previewMatches =
    state.restorePreviewKind === kind &&
    state.restorePreviewVerified &&
    state.restorePreviewBackupPath &&
    state.restorePreviewBackupPath === expectedBackupPath;
  if (!previewMatches) {
    log(text.needRestorePreview);
    if (isLatest) {
      await previewRestore(null);
    }
    return;
  }
  const confirmed = window.confirm(text.confirmRestore);
  if (!confirmed) return;
  const result = await api("/api/restore", {
    method: "POST",
    body: JSON.stringify({ backup: expectedBackupPath }),
  });
  renderStatus(result.status);
  resetRestorePreview();
  setWriteState();
  log(`${text.restoreComplete}: ${result.restored_from}`);
}

async function showManifest() {
  if (!state.selectedBackup) return;
  const result = await api("/api/manifest/open", {
    method: "POST",
    body: JSON.stringify({ backup: state.selectedBackup }),
  });
  log(`${text.opened}: ${result.path}`);
}

async function openBackups() {
  const result = await api("/api/backups/open", { method: "POST", body: "{}" });
  log(`${text.opened}: ${result.path}`);
}

function scrollToSection(targetId) {
  const target = document.querySelector(`#${targetId}`);
  if (target) target.scrollIntoView({ behavior: "smooth", block: "start" });
}

function setActiveNav(button) {
  document.querySelectorAll("nav button").forEach((item) => item.classList.remove("active"));
  button.classList.add("active");
}

function wireNav() {
  document.querySelectorAll("nav button").forEach((button) => {
    button.addEventListener("click", () => {
      setActiveNav(button);
      scrollToSection(button.dataset.navTarget || "top");
      if (button.dataset.navAction === "dryRun") {
        dryRun().catch((error) => log(`${text.error}: ${error.message}`));
      } else if (button.dataset.navAction === "restorePreview") {
        previewRestore().catch((error) => log(`${text.error}: ${error.message}`));
      } else if (button.dataset.navTarget === "activity") {
        log(text.settingsHint);
      }
    });
  });
}

for (const [element, handler] of [
  [elements.scopeToggle, refresh],
  [elements.dryRunButton, dryRun],
  [elements.syncButton, syncNow],
  [elements.backupButton, backup],
  [elements.restorePreviewButton, previewRestore],
  [elements.restoreSelectedButton, () => restoreBackup("selected")],
  [elements.restoreLatestButton, () => restoreBackup("latest")],
  [elements.manifestButton, showManifest],
  [elements.openBackupsButton, openBackups],
]) {
  element.addEventListener("click", () => {
    handler().catch((error) => log(`${text.error}: ${error.message}`));
  });
}

elements.cwdInput.addEventListener("input", () => {
  state.syncPreviewReady = false;
  setWriteState();
});

applyText();
wireNav();
setWriteState();
doctor()
  .catch((error) => log(`${text.startupFailed}: ${error.message}`))
  .finally(() => refresh().catch((error) => log(`${text.startupFailed}: ${error.message}`)));
